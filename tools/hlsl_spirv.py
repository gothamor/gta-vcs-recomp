#!/usr/bin/env python3
"""HLSL -> SPIR-V for the Vulkan RHI backend (src/render/CMakeLists.txt runs it at build time). Standard library only.

    python tools/hlsl_spirv.py --glslang PATH --stage vert|frag --entry vs_main --name kGsDrawVS_spv
                               --out gs_draw_vs.spv.h [-D NAME=VALUE ...] SOURCE.hlsl

The same HLSL as fxc's DXBC (one source, docs/NATIVE_RENDERER.md). glslang compiles it; the bindings follow the D3D11
registers (src/rhi/vulkan/rhi_vulkan.cpp has the layout): cbuffer bN -> binding N, texture tN -> 16 + N, sampler
sN -> 32 + N, all in set 0.

Dual-source blending: D3D11 takes SV_Target1 as the second source of target 0; Vulkan wants Location 0 Index 1, and
glslang ignores [[vk::index(1)]] in HLSL. The output variable `@entryPointOutput.blend` (PSOut.blend in gs_draw.hlsl)
is moved to Location 0 Index 1 here.

VCS_SPIRV=1 is defined for the HLSL (Vulkan-only parts: the point size).

The header holds `static const unsigned char <name>[]` (the words little-endian, as the device reads them).
"""
import argparse
import os
import struct
import subprocess
import sys
import tempfile

SPIRV_MAGIC = 0x07230203
OP_NAME = 5
OP_DECORATE = 71
DECORATION_LOCATION = 30
DECORATION_INDEX = 32
DUAL_SOURCE_OUTPUT = "@entryPointOutput.blend"


def words_of(data):
    if len(data) % 4:
        raise ValueError("SPIR-V size is not a whole number of words")
    words = list(struct.unpack("<%dI" % (len(data) // 4), data))
    if words[0] != SPIRV_MAGIC:
        raise ValueError("not SPIR-V (magic %08x)" % words[0])
    return words


def instructions(words):
    """(position, opcode, word count) of each instruction after the 5-word header."""
    pos = 5
    while pos < len(words):
        count, opcode = words[pos] >> 16, words[pos] & 0xFFFF
        if count == 0:
            raise ValueError("SPIR-V instruction with no words at %d" % pos)
        yield pos, opcode, count
        pos += count


def literal_string(words, start, end):
    raw = struct.pack("<%dI" % (end - start), *words[start:end])
    return raw.split(b"\0", 1)[0].decode("utf-8", "replace")


def patch_dual_source(words):
    """Moves the second colour output to Location 0 Index 1. Returns the patched words (unchanged without one)."""
    target = None
    for pos, opcode, count in instructions(words):
        if opcode == OP_NAME and literal_string(words, pos + 2, pos + count) == DUAL_SOURCE_OUTPUT:
            target = words[pos + 1]
            break
    if target is None:
        return words
    for pos, opcode, count in instructions(words):
        if opcode == OP_DECORATE and count == 4 and words[pos + 1] == target and words[pos + 2] == DECORATION_LOCATION:
            words = list(words)
            words[pos + 3] = 0
            index = [(4 << 16) | OP_DECORATE, target, DECORATION_INDEX, 1]
            return words[:pos + count] + index + words[pos + count:]
    raise ValueError(DUAL_SOURCE_OUTPUT + " has no Location decoration")


def write_header(path, name, words, source):
    data = struct.pack("<%dI" % len(words), *words)
    lines = ["// Generated by tools/hlsl_spirv.py from %s - do not edit." % os.path.basename(source),
             "#pragma once", "static const unsigned char %s[] = {" % name]
    for i in range(0, len(data), 24):
        lines.append("    " + ", ".join("0x%02x" % b for b in data[i:i + 24]) + ",")
    lines.append("};")
    tmp = path + ".tmp"
    with open(tmp, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    os.replace(tmp, path)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--glslang", default="glslangValidator")
    ap.add_argument("--stage", required=True, choices=("vert", "frag"))
    ap.add_argument("--entry", required=True)
    ap.add_argument("--name", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("-D", dest="defines", action="append", default=[])
    ap.add_argument("source")
    a = ap.parse_args()

    fd, spv = tempfile.mkstemp(suffix=".spv", dir=os.path.dirname(os.path.abspath(a.out)))
    os.close(fd)
    try:
        cmd = [a.glslang, "-D", "-V", "--target-env", "vulkan1.3", "--shift-texture-binding", "16",
               "--shift-sampler-binding", "32"]
        cmd += ["-DVCS_SPIRV=1"] + ["-D" + d for d in a.defines]
        # the entry point is called "main" in every module (the device needs no name per shader)
        cmd += ["-S", a.stage, "-e", "main", "--source-entrypoint", a.entry, "-o", spv, a.source]
        result = subprocess.run(cmd, capture_output=True, text=True)
        if result.returncode != 0:
            sys.stderr.write(result.stdout + result.stderr)
            sys.exit("hlsl_spirv: glslang failed on %s %s" % (a.source, a.entry))
        with open(spv, "rb") as f:
            words = patch_dual_source(words_of(f.read()))
    finally:
        os.remove(spv)
    write_header(a.out, a.name, words, a.source)


if __name__ == "__main__":
    main()
