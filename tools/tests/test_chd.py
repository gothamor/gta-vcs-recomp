"""tools/chd.py: a CHD v5 reads back as the 2048-byte sectors it was made from (docs/DISC.md "CHD images").

The CHDs are built by tests/chd_build.py from generated bytes, no game data. The last test reads the player's own
disc/vcs.chd against the ISO next to it, and skips when they are missing.

    python -m unittest discover tools/tests
"""
import os
import random
import struct
import sys
import tempfile
import unittest

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.dirname(HERE))
sys.path.insert(0, HERE)
import chd  # noqa: E402
import chd_build as cb  # noqa: E402
import vcs_disc  # noqa: E402

SECTOR = 2048
CD_META = b"TRACK:1 TYPE:MODE1 SUBTYPE:NONE FRAMES:%d PREGAP:0 PGTYPE:MODE1 PGSUB:NONE POSTGAP:0\0"


def pseudo_random(n, seed):
    rng = random.Random(seed)
    # compressible but not trivial: runs of a few values, like real disc data
    out = bytearray()
    while len(out) < n:
        out += bytes([rng.randrange(4)]) * rng.randrange(1, 40)
    return bytes(out[:n])


DVD_DEFAULT_CODECS = (b"lzma", b"zlib", b"huff", b"flac")  # chdman createdvd's defaults


def dvd_chd(sectors, plan, compressors=(b"lzma", b"zlib", b"\0\0\0\0", b"\0\0\0\0"), per_hunk=2, **kw):
    hunk_bytes = SECTOR * per_hunk
    data = b"".join(sectors)
    data += bytes(-len(data) % hunk_bytes)
    hunks = [data[i:i + hunk_bytes] for i in range(0, len(data), hunk_bytes)]
    return cb.build_chd(hunks, hunk_bytes, SECTOR, list(compressors), plan, [(b"DVD ", b"\0")],
                        logical_bytes=len(sectors) * SECTOR, **kw)


def cd_chd(sectors, plan, compressors=(b"cdlz", b"cdzl", b"cdfl", b"\0\0\0\0"), frames_per_hunk=2, **kw):
    frames = []
    for s in sectors:
        frames.append(s + bytes(cb.CD_SECTOR - SECTOR) + bytes(cb.CD_SUB))  # MODE1: 2048 data, padding, no subcode
    while len(frames) % frames_per_hunk:
        frames.append(bytes(cb.CD_FRAME))
    hunk_bytes = cb.CD_FRAME * frames_per_hunk
    data = b"".join(frames)
    hunks = [data[i:i + hunk_bytes] for i in range(0, len(data), hunk_bytes)]
    meta = [(b"CHT2", CD_META % len(sectors))]
    return cb.build_chd(hunks, hunk_bytes, cb.CD_FRAME, list(compressors), plan, meta,
                        logical_bytes=len(hunks) * hunk_bytes, **kw)


def iso_sectors():
    """A tiny ISO 9660 image: PVD at 16, root directory at 18, SYSTEM.CNF at 19 (enough for vcs_disc.IsoImage)."""
    cnf = b"BOOT2 = cdrom0:\\SLUS_215.90;1\r\nVER = 1.00\r\n"

    def record(name, lba, size, is_dir):
        n = len(name)
        rec = bytearray(33 + n + (1 - n % 2))
        rec[0] = len(rec)
        struct.pack_into("<I", rec, 2, lba)
        struct.pack_into(">I", rec, 6, lba)
        struct.pack_into("<I", rec, 10, size)
        struct.pack_into(">I", rec, 14, size)
        rec[25] = 2 if is_dir else 0
        rec[32] = n
        rec[33:33 + n] = name
        return bytes(rec)

    sectors = [bytes(SECTOR)] * 22
    pvd = bytearray(SECTOR)
    pvd[0] = 1
    pvd[1:6] = b"CD001"
    pvd[40:72] = b"TESTDISC".ljust(32)
    pvd[156:190] = record(b"\0", 18, SECTOR, True)[:34]
    sectors[16] = bytes(pvd)
    root = record(b"\0", 18, SECTOR, True) + record(b"\1", 18, SECTOR, True) + record(b"SYSTEM.CNF;1", 19, len(cnf), False)
    sectors[18] = root + bytes(SECTOR - len(root))
    sectors[19] = cnf + bytes(SECTOR - len(cnf))
    sectors[20] = pseudo_random(SECTOR, 7)
    sectors[21] = pseudo_random(SECTOR, 8)
    return sectors


class ChdReader(unittest.TestCase):
    def setUp(self):
        self.dir = tempfile.TemporaryDirectory()

    def tearDown(self):
        self.dir.cleanup()

    def write(self, data, name="t.chd"):
        path = os.path.join(self.dir.name, name)
        with open(path, "wb") as f:
            f.write(data)
        return path

    def assertSectors(self, path, sectors):
        with chd.ChdImage(path) as img:
            self.assertEqual(img.sector_count, len(sectors))
            for lba, want in enumerate(sectors):
                self.assertEqual(img.read_sectors(lba, 1), want, "sector %d" % lba)
            self.assertEqual(img.read_sectors(0, len(sectors)), b"".join(sectors))  # across hunks
            self.assertEqual(img.read_sectors(len(sectors) - 1, 5), sectors[-1])    # short at the end, like a file

    def test_dvd_every_hunk_kind(self):
        sectors = [pseudo_random(SECTOR, i) for i in range(10)]
        sectors[6:8] = sectors[0:2]  # hunk 3 repeats hunk 0: a self reference
        plan = [("c", 0), ("c", 1), ("none",), ("self", 0), ("c", 0)]
        self.assertSectors(self.write(dvd_chd(sectors, plan)), sectors)

    def test_dvd_kind_and_metadata(self):
        sectors = [pseudo_random(SECTOR, 1)] * 2
        with chd.ChdImage(self.write(dvd_chd(sectors, [("c", 1)]))) as img:
            self.assertEqual(img.kind, "dvd")

    def test_cd_mode1_every_codec(self):
        sectors = [pseudo_random(SECTOR, 100 + i) for i in range(7)]
        plan = [("c", 0), ("c", 1), ("c", 2), ("c", 0)]
        path = self.write(cd_chd(sectors, plan))
        with chd.ChdImage(path) as img:
            self.assertEqual(img.kind, "cd")
        self.assertSectors(path, sectors)

    def test_hunk_crc_mismatch_is_refused(self):
        sectors = [pseudo_random(SECTOR, i) for i in range(4)]
        path = self.write(dvd_chd(sectors, [("c", 0), ("c", 1)], break_crc=1))
        with chd.ChdImage(path) as img:
            self.assertEqual(img.read_sectors(0, 2), b"".join(sectors[:2]))
            with self.assertRaisesRegex(chd.ChdError, "CRC"):
                img.read_sectors(2, 1)

    def test_map_crc_mismatch_is_refused(self):
        sectors = [pseudo_random(SECTOR, i) for i in range(4)]
        path = self.write(dvd_chd(sectors, [("c", 0), ("c", 1)], break_map_crc=True))
        with self.assertRaisesRegex(chd.ChdError, "map"):
            chd.ChdImage(path)

    def test_dvd_chdmans_default_codecs(self):
        # chdman createdvd compresses with the hard-disk defaults: lzma, zlib, huff, flac (MAME chdman.cpp
        # s_default_hd_compression); flac's first byte gives the samples' byte order, L or B
        sectors = [pseudo_random(SECTOR, 20 + i) for i in range(8)]
        plan = [("c", 0), ("c", 1), ("c", 2), ("c", 3)]
        for endian in ("L", "B"):
            path = self.write(dvd_chd(sectors, plan, compressors=DVD_DEFAULT_CODECS, enc=cb.Encoding(flac_endian=endian)),
                              "default_%s.chd" % endian)
            self.assertSectors(path, sectors)

    def test_unknown_codec_is_named(self):
        sectors = [pseudo_random(SECTOR, i) for i in range(2)]
        path = self.write(dvd_chd(sectors, [("c", 0)], compressors=(b"avhu", b"\0\0\0\0", b"\0\0\0\0", b"\0\0\0\0")))
        with chd.ChdImage(path) as img:
            with self.assertRaisesRegex(chd.ChdError, "avhu"):
                img.read_sectors(0, 1)

    def test_not_a_chd(self):
        with self.assertRaises(chd.ChdError):
            chd.ChdImage(self.write(b"plain bytes, no header", "x.chd"))

    def test_flac_every_subframe_kind(self):
        # chd_build.flac_encode -> chd._flac_decode, one frame plan at a time (left / right, left / side, side /
        # right, mid / side; CONSTANT, VERBATIM, FIXED 0-4, LPC, wasted bits, two Rice partitions)
        import math
        n = 2 * 1176
        left = [int(9000 * math.sin(i / 9.0)) * 2 for i in range(n)]       # even: room for a wasted bit
        right = [int(7000 * math.cos(i / 13.0)) for i in range(n)]
        lpc = {"kind": "lpc", "coefs": [1900, -880], "shift": 10, "precision": 13}
        cases = {
            "left/right fixed 2 + lpc": (1, {"kind": "fixed", "order": 2}, lpc, left, right),
            "left/side wasted + verbatim": (8, {"kind": "fixed", "order": 1, "wasted": 1}, {"kind": "verbatim"}, left, right),
            "side/right fixed 3 + 4": (9, {"kind": "fixed", "order": 3}, {"kind": "fixed", "order": 4}, left, right),
            "mid/side fixed 0 + constant": (10, {"kind": "fixed", "order": 0}, {"kind": "constant"},
                                            left, [v - 1234 for v in left]),
        }
        for name, (chan, s0, s1, l, r) in cases.items():
            with self.subTest(name):
                samples = [v for pair in zip(l, r) for v in pair]
                data = cb.flac_encode(samples, 1176, [(chan, s0, s1)])
                decoded, used = chd._flac_decode(data, n)
                self.assertEqual(decoded, samples)
                self.assertEqual(used, len(data))

    def test_cd_flac_hunks(self):
        sectors = [pseudo_random(SECTOR, 300 + i) for i in range(16)]
        plans = [(10, {"kind": "fixed", "order": 2}, {"kind": "fixed", "order": 1}),
                 (9, {"kind": "lpc", "coefs": [1500, -500], "shift": 10, "precision": 12}, {"kind": "fixed", "order": 0}),
                 (8, {"kind": "verbatim"}, {"kind": "fixed", "order": 3}),
                 (1, {"kind": "fixed", "order": 4}, {"kind": "verbatim"})]
        path = self.write(cd_chd(sectors, [("c", 2), ("c", 2)], frames_per_hunk=8, enc=cb.Encoding(flac_plans=plans)))
        self.assertSectors(path, sectors)

    def test_cd_raw_track_with_removed_ecc(self):
        # MODE1_RAW: data at 16; frames 0, 2 and 5 stored without sync / ECC (chdman's ECC flag)
        sectors = [pseudo_random(SECTOR, 500 + i) for i in range(6)]
        frames = cb.raw_mode1_frames(sectors)
        hunk_bytes = cb.CD_FRAME * 2
        data = b"".join(frames)
        hunks = [data[i:i + hunk_bytes] for i in range(0, len(data), hunk_bytes)]
        meta = [(b"CHT2", b"TRACK:1 TYPE:MODE1_RAW SUBTYPE:NONE FRAMES:6 PREGAP:0 PGTYPE:MODE1 PGSUB:NONE POSTGAP:0\0")]
        chd_bytes = cb.build_chd(hunks, hunk_bytes, cb.CD_FRAME, [b"cdlz", b"cdzl", b"\0\0\0\0", b"\0\0\0\0"],
                                 [("c", 0), ("c", 1), ("c", 0)], meta, enc=cb.Encoding(ecc_frames=(0, 2, 5)))
        self.assertSectors(self.write(chd_bytes), sectors)

    def test_stored_pregap_is_refused(self):
        sectors = [pseudo_random(SECTOR, i) for i in range(4)]
        data = cd_chd(sectors, [("c", 1), ("c", 1)])
        data = data.replace(b"PREGAP:0 PGTYPE:MODE1", b"PREGAP:2 PGTYPE:VMODE")  # same length: offsets stay
        with self.assertRaisesRegex(chd.ChdError, "pregap"):
            chd.ChdImage(self.write(data))

    def test_track_longer_than_the_data_is_refused(self):
        sectors = [pseudo_random(SECTOR, i) for i in range(4)]
        data = cd_chd(sectors, [("c", 1), ("c", 1)]).replace(b"FRAMES:4 ", b"FRAMES:9 ")
        with self.assertRaisesRegex(chd.ChdError, "longer"):
            chd.ChdImage(self.write(data))

    def test_iso_reader_closes_a_chd_that_is_no_disc(self):
        sectors = [pseudo_random(SECTOR, i) for i in range(18)]  # no ISO 9660 volume descriptor at 16
        path = self.write(dvd_chd(sectors, [("c", 0)] * 9), "nodisc.chd")
        with self.assertRaises(ValueError):
            vcs_disc.IsoImage(path)
        os.remove(path)  # Windows refuses while a handle is open

    def test_iso_reader_on_a_chd(self):
        sectors = iso_sectors()
        plan = [("c", i % 2) for i in range(len(sectors) // 2)]
        path = self.write(dvd_chd(sectors, plan), "disc.chd")
        with vcs_disc.IsoImage(path) as img:
            self.assertEqual(img.volume_id, "TESTDISC")
            rec = img.find("SYSTEM.CNF")
            self.assertIsNotNone(rec)
            self.assertIn(b"SLUS_215.90", img.read_file(rec))

    def test_iso_reader_on_a_cd_mode_chd(self):
        sectors = iso_sectors()
        plan = [("c", i % 3) for i in range(len(sectors) // 2)]
        with vcs_disc.IsoImage(self.write(cd_chd(sectors, plan), "disc.chd")) as img:
            self.assertIn(b"SLUS_215.90", img.read_file(img.find("SYSTEM.CNF")))


ROOT = os.path.dirname(os.path.dirname(HERE))
# The player's own disc as a CHD and as the ISO it was made from: checks, not regression tests (they need game data),
# so opt-in: VCS_TEST_PLAYER_DISC=1, with disc/vcs.chd and disc/vcs.iso, or VCS_PLAYER_CHD / VCS_PLAYER_ISO
PLAYER_CHD = os.environ.get("VCS_PLAYER_CHD") or os.path.join(ROOT, "disc", "vcs.chd")
PLAYER_ISO = os.environ.get("VCS_PLAYER_ISO") or os.path.join(ROOT, "disc", "vcs.iso")
PLAYER_DISC = os.environ.get("VCS_TEST_PLAYER_DISC") == "1" and os.path.isfile(PLAYER_CHD) and os.path.isfile(PLAYER_ISO)
PLAYER_DISC_WHY = "the player's disc: VCS_TEST_PLAYER_DISC=1 with VCS_PLAYER_CHD / VCS_PLAYER_ISO (disc/vcs.chd, disc/vcs.iso)"


@unittest.skipUnless(PLAYER_DISC, PLAYER_DISC_WHY)
class PlayersDisc(unittest.TestCase):
    def test_sampled_sectors_match_the_iso(self):
        with chd.ChdImage(PLAYER_CHD) as img, open(PLAYER_ISO, "rb") as iso:
            total = os.path.getsize(PLAYER_ISO) // SECTOR
            self.assertEqual(img.sector_count, total)
            lbas = list(range(0, 64)) + list(range(0, total, 9973)) + list(range(total - 64, total))
            for lba in lbas:
                iso.seek(lba * SECTOR)
                self.assertEqual(img.read_sectors(lba, 1), iso.read(SECTOR), "sector %d" % lba)

    def test_check_finds_the_executable(self):
        with vcs_disc.IsoImage(PLAYER_CHD) as img:
            self.assertIsNotNone(img.find(vcs_disc.ELF_NAME))


if __name__ == "__main__":
    unittest.main()
